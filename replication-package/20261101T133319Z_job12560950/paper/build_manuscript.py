#!/usr/bin/env python3
"""
build_manuscript.py — compile a JPE_submission_vN.tex that uses \\input of
package-generated table fragments.

WHY THIS EXISTS
---------------
The manuscript \\input's ~41 partial table-row fragments (regression results)
that are generated by the replication package. With the current TeX
distribution, a partial-row fragment brought in via \\input and immediately
followed by a booktabs \\noalign command (\\bottomrule / \\addlinespace /
\\cmidrule) triggers a fatal "Misplaced \\noalign" error. The identical content
compiles fine when INLINED rather than \\input. (This became fatal after a TeX
upgrade; the manuscript compiled previously.)

This script resolves the issue by SPLICING: it inlines only the partial-row
fragments (files with no \\begin{tabular}/\\begin{table} of their own) directly
into a build copy, leaving full-table \\input's and \\includegraphics untouched,
then compiles the build copy with bibtex. The SOURCE .tex keeps clean \\input's
for editing/version control; only the build copy is spliced.

USAGE
-----
    python3 build_manuscript.py JPE_submission_v5.tex
Produces JPE_submission_v5_build.tex and JPE_submission_v5_build.pdf.
"""

import datetime
import os
import re
import subprocess
import sys
import tempfile
import time


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python3 build_manuscript.py JPE_submission_vN.tex")
    src_name = sys.argv[1]
    base = os.path.dirname(os.path.abspath(src_name)) or os.getcwd()
    src = open(src_name, encoding="utf-8").read()

    # Resolve the output-tree prefix so the SAME script compiles in either layout:
    #   - editor tree:  paper/../replication_package/output  exists (a symlinked mirror) -> paths as-is
    #   - deposit tree: paper/../replication_package/output  is absent, but paper/../output holds the
    #                   packaged exhibits. The manuscript's live \input/\includegraphics all use the
    #                   ../replication_package/output/ prefix, so rewrite it to ../output/ in the build
    #                   copy. This is the build-time path rewrite that makes the deposit self-contained
    #                   (JPE: the manuscript must compile from the package). The SOURCE .tex is
    #                   untouched; only the _build.tex copy is rewritten.
    EDITOR_PREFIX = "../replication_package/output/"
    DEPOSIT_PREFIX = "../output/"
    if not os.path.isdir(os.path.join(base, "../replication_package/output")) \
            and os.path.isdir(os.path.join(base, "../output")):
        n = src.count(EDITOR_PREFIX)
        src = src.replace(EDITOR_PREFIX, DEPOSIT_PREFIX)
        print(f"Deposit layout detected: rewrote {n} '{EDITOR_PREFIX}' -> '{DEPOSIT_PREFIX}' prefix(es).")

    inlined, left = [], []

    def repl(m):
        path = m.group(1)
        full = os.path.normpath(os.path.join(base, path))
        if not os.path.exists(full):
            left.append(path + " (missing)")
            return m.group(0)
        content = open(full, encoding="utf-8", errors="replace").read()
        # Inline ONLY partial-row fragments (no environment of their own).
        # Full-table files keep their \input (they are self-contained and do
        # not abut a \noalign across the input boundary).
        if "\\begin{tabular}" in content or "\\begin{table}" in content:
            left.append(path + " (full table)")
            return m.group(0)
        inlined.append(path)
        # Pure substitution. Strip a trailing newline so the fragment's final
        # \\ does not sit on its own before the following \noalign.
        return content.rstrip("\n")

    # Process line by line so a commented-out \input is never inlined
    # (a commented \input would leave the fragment's first line commented and
    # spill the rest onto live lines -> stray "&" errors).
    out_lines = []
    for line in src.splitlines(keepends=True):
        # find the first unescaped % (comment start) on this line
        cpos = None
        i = 0
        while i < len(line):
            if line[i] == "%" and (i == 0 or line[i - 1] != "\\"):
                cpos = i
                break
            i += 1
        if cpos is None:
            out_lines.append(re.sub(r"\\input\{([^}]+\.tex)\}", repl, line))
        else:
            # only substitute in the code part (before the comment)
            code, comment = line[:cpos], line[cpos:]
            out_lines.append(re.sub(r"\\input\{([^}]+\.tex)\}", repl, code) + comment)
    out = "".join(out_lines)
    build_name = src_name.replace(".tex", "_build.tex")
    open(build_name, "w", encoding="utf-8").write(out)
    print(f"Inlined {len(inlined)} partial-row fragments; left {len(left)} "
          f"(full-table/missing) as \\input.")
    print(f"Wrote {build_name}; compiling...")

    stem = build_name[:-4]
    cmds = [
        ("pdflatex", ["pdflatex", "-interaction=nonstopmode", build_name]),
        ("bibtex",   ["bibtex", stem]),
        ("pdflatex", ["pdflatex", "-interaction=nonstopmode", build_name]),
        ("pdflatex", ["pdflatex", "-interaction=nonstopmode", build_name]),
    ]
    # Deterministic PDF build (the git-tracked _build.pdf is classified as source and
    # hash-verified for provenance, so it MUST be byte-reproducible -- otherwise a fresh --final compile,
    # which embeds a wall-clock /CreationDate + /ModDate + a random trailer /ID, would never match its
    # committed hash). pdfTeX honours SOURCE_DATE_EPOCH for /CreationDate + /ModDate, and with
    # FORCE_SOURCE_DATE=1 derives the trailer /ID from it as well, so a FIXED epoch + fixed content +
    # the pinned TeX toolchain (the deposit SIF) produce byte-identical output every build. The epoch is
    # a fixed project constant, never the wall clock. NOTE: the committed _build.pdf must be REGENERATED
    # once under this setting (in the pinned SIF) so its committed bytes are the reproducible ones.
    # The title page prints \today, which pdfTeX also takes from SOURCE_DATE_EPOCH, so the pinned epoch is
    # the manuscript's BUILD DATE (author decision, 2026-09-14: the title page shows the latest build date).
    # Set MANUSCRIPT_BUILD_DATE to the day of each new authoritative build; rebuilding the same content with
    # the same date stays byte-identical. Noon UTC keeps the printed date the same in US time zones.
    MANUSCRIPT_BUILD_DATE = "2026-09-15"
    SOURCE_DATE_EPOCH = str(int(datetime.datetime.strptime(MANUSCRIPT_BUILD_DATE, "%Y-%m-%d")
                                .replace(hour=12, tzinfo=datetime.timezone.utc).timestamp()))
    build_env = dict(os.environ)
    build_env["SOURCE_DATE_EPOCH"] = SOURCE_DATE_EPOCH
    build_env["FORCE_SOURCE_DATE"] = "1"

    # Fail-open compile gate (fixed): the OLD gate ignored pdflatex's return
    # code entirely and accepted ANY pre-existing "{stem}.pdf" as proof the build worked. The
    # failing fixture: three fake pdflatex calls that all return rc=1, produce no PDF, and emit no
    # "! " marker, plus a STALE {stem}.pdf already sitting on disk -- the old gate exited 0 and
    # printed "BUILD OK". Fix, in order:
    #   (1) delete every target build product BEFORE compiling, so mere existence afterward cannot
    #       be a leftover from a prior (possibly failed) run;
    #   (2) require rc==0 from EVERY required tool call (each pdflatex pass AND bibtex) -- no
    #       tool-specific carve-out, no "warnings are fine" allowance;
    #   (3) require the resulting PDF to be FRESHLY created (mtime at/after this run's start) and
    #       non-empty, as defense-in-depth on top of (1);
    #   (4) keep the "! "-line log scan and missing-\input/\includegraphics scan as ADDITIONAL
    #       checks, not substitutes for (2).
    # Verified locally (TeX Live 2026, pdfTeX 3.141592653-2.6-1.40.29) that rc==0 is the correct bar
    # for a genuine clean build, not just a convenient one: a first pdflatex pass with "No file
    # X.aux"/"No file X.bbl", "Citation ... undefined", and "There were undefined references"
    # (all expected before bibtex/later passes resolve them), and a bibtex pass with a
    # "Warning--empty journal in X" bib-entry warning, both exit rc=0. A real content error (e.g. an
    # undefined control sequence) exits rc=1 even though pdflatex, under -interaction=nonstopmode,
    # still emits a placeholder PDF -- which is exactly why rc, not "a PDF got written", is the gate.
    _build_products = [
        stem + ext for ext in
        (".pdf", ".aux", ".bbl", ".blg", ".log", ".out", ".toc", ".lof", ".lot", ".synctex.gz")
    ]
    for _p in _build_products:
        try:
            os.remove(_p)
        except FileNotFoundError:
            pass
    build_start_time = time.time()

    combined, hard_fail = [], []
    for name, c in cmds:
        try:
            r = subprocess.run(c, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=build_env)
        except FileNotFoundError:
            print(f"BUILD FAILED: required tool '{c[0]}' not found on PATH "
                  f"(the compile gate must not pass without a working LaTeX toolchain).")
            sys.exit(1)
        combined.append(f"===== {name} (rc={r.returncode}) =====\n{r.stdout or ''}")
        if r.returncode != 0:
            hard_fail.append(f"{name} exited {r.returncode} (rc must be 0)")
    # Rerun pdflatex while the last pass asks for it, at most twice. TeX Live 2019 in the certification
    # image needs a 4th pass on this manuscript to settle its cross-references; TeX Live 2026 settles in 3.
    # A final pass that still asks is caught downstream by the packaging compile gate.
    for _ in range(2):
        try:
            _last = open(stem + ".log", encoding="latin-1").read().replace("\n", "")
        except OSError:
            break
        if "Label(s) may have changed" not in _last and "Rerun to get" not in _last:
            break
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode", build_name],
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=build_env)
        combined.append(f"===== pdflatex rerun (rc={r.returncode}) =====\n{r.stdout or ''}")
        if r.returncode != 0:
            hard_fail.append(f"pdflatex rerun exited {r.returncode} (rc must be 0)")
    log = "\n".join(combined)
    # Full multi-pass compile log, retained for debugging. Written to the platform temp directory
    # under a unique name rather than the fixed path /tmp/_bm.log: /tmp is not writable (or not
    # private) in every container, and a fixed name lets two builds overwrite each other's evidence.
    _fd, _log_path = tempfile.mkstemp(prefix=f"{stem}_build_passes_", suffix=".log", text=True)
    with os.fdopen(_fd, "w") as _fh:
        _fh.write(log)
    print(f"Full multi-pass compile log: {_log_path}")
    errs = [l for l in log.splitlines() if l.startswith("! ")]
    # Missing \input / \includegraphics files degrade silently under nonstopmode; treat them as errors
    # so the compile gate cannot pass with blank figure boxes. EXCLUDE LaTeX auto-generated
    # intermediates (.aux/.bbl/.toc/.out ...): they are legitimately absent on the FIRST pass (created
    # by later passes). Because ALL passes' logs are retained (to catch bibtex/earlier errors),
    # those benign first-pass "No file X.aux" messages must be filtered so they do not read as
    # a missing exhibit.
    _autogen = re.compile(r"No file \S+\.(aux|bbl|blg|toc|out|lof|lot|nav|snm|idx|ind|synctex)\b")
    missing_files = [l for l in log.splitlines()
                     if ("No file" in l or ("not found" in l and ("includegraphics" in l.lower()
                          or ".png" in l or ".pdf" in l or ".tex" in l)))
                     and not _autogen.search(l)]
    # Use the LAST "Output written" match, not the first: the log concatenates all passes (pdflatex,
    # bibtex, pdflatex, pdflatex), and the FIRST pdflatex pass runs BEFORE bibtex populates citations,
    # so its reported page count is not yet stable (found 2026-09-04: it under-reported by 8pp vs the
    # final PDF's actual, pdfinfo-verified page count on this manuscript).
    _page_matches = re.findall(r"Output written.*\((\d+) page", log)
    pages_str = _page_matches[-1] if _page_matches else None
    # Require a FRESHLY-created, non-empty PDF -- not a pre-existing/stale one (see the gate note above).
    # Build products were deleted above, so mere existence now already implies THIS run wrote the
    # file; the size/mtime checks are belt-and-suspenders against a tool that leaves behind a
    # zero-byte placeholder or an artifact with a suspiciously old timestamp.
    pdf_path = stem + ".pdf"
    pdf_ok = False
    if os.path.exists(pdf_path):
        _st = os.stat(pdf_path)
        pdf_ok = _st.st_size > 0 and _st.st_mtime >= build_start_time - 2
    print(f"  remaining errors: {len(errs)}")
    for e in errs[:8]:
        print("   ", e)
    for mf in missing_files[:8]:
        print("   MISSING:", mf.strip())
    for hf in hard_fail:
        print("   TOOL-FAILURE:", hf)
    print(f"  pages: {pages_str if pages_str else 'NONE'}")
    if errs or missing_files or not pdf_ok or hard_fail:
        print(f"BUILD FAILED (errors={len(errs)}, missing_files={len(missing_files)}, "
              f"tool_failures={len(hard_fail)}, pdf={'yes' if pdf_ok else 'NO'}).")
        sys.exit(1)
    print(f"BUILD OK: {stem}.pdf ({pages_str if pages_str else '?'} pages).")
    sys.exit(0)


if __name__ == "__main__":
    main()
