#!/usr/bin/env python3
"""compare_exhibit_fidelity.py -- the real-data route's exhibit-fidelity gate.

Every manuscript exhibit that the real-data run regenerates must match the committed exhibit the manuscript
shows. The reference set is the package's own manuscript closure (certification/MANUSCRIPT_CLOSURE.sha256):
every \\input table and \\includegraphics figure under output/. For each exhibit:
  * the committed copy under --reference-root must still match its closure pin, so the reference is bound to
    the package;
  * a regenerated .tex table must be byte-identical to the committed copy;
  * a regenerated PNG figure must decode to the same size and the same RGBA pixel values. PNG metadata may
    differ: the certification image re-encodes some figures without changing a pixel;
  * a declared static copy (STATIC_EXHIBITS, copied rather than computed) must be byte-identical to its pin;
  * any other file type must be byte-identical;
  * an exhibit the run did not regenerate fails.
Exit 0 only when every exhibit passes. The last line is EXHIBIT_FIDELITY_FAILURES=<n>.

    python3 certification/compare_exhibit_fidelity.py --regen-root <work copy> --reference-root <package>
"""
import argparse
import hashlib
import sys
from pathlib import Path

# Figures no analysis step computes: 11g_descriptive_figures.py copies them from data/raw/ (the producer map in
# code/audit_pipeline.py says so). They are checked against their pins, not compared as computations.
STATIC_EXHIBITS = frozenset({
    "output/figures/Data_new_latest.png",
    "output/figures/Deregulation_May31_23_Paper.png",
})


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def closure_exhibits(closure):
    """[(relpath, pinned sha256)] for every closure entry under output/."""
    out = []
    for line in Path(closure).read_text(encoding="utf-8").splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2 and parts[1].strip().startswith("output/"):
            out.append((parts[1].strip(), parts[0].strip().lower()))
    return out


def _pixels(path):
    import numpy as np
    from PIL import Image
    with Image.open(path) as im:
        rgba = im.convert("RGBA")
        return rgba.size, np.asarray(rgba)


def exhibit_problem(rel, pin, regen_root, ref_root):
    """None if the regenerated exhibit matches the committed one, else why not."""
    ref, regen = ref_root / rel, regen_root / rel
    if not ref.is_file():
        return f"the committed copy is missing from the reference: {rel}"
    if sha256(ref) != pin:
        return f"the committed copy no longer matches its closure pin: {rel}"
    if not regen.is_file():
        return f"not regenerated by this run: {rel}"
    if rel in STATIC_EXHIBITS or not rel.lower().endswith(".png"):
        return None if sha256(regen) == pin else f"bytes differ from the committed exhibit: {rel}"
    try:
        (size_regen, px_regen), (size_ref, px_ref) = _pixels(regen), _pixels(ref)
    except Exception as e:  # undecodable image data
        return f"cannot decode: {rel} ({e})"
    if size_regen != size_ref:
        return f"image size {size_regen} differs from the committed {size_ref}: {rel}"
    differing = int((px_regen != px_ref).any(axis=-1).sum())
    return None if differing == 0 else f"{differing} pixels differ from the committed figure: {rel}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--regen-root", required=True, type=Path, help="package root whose output/ the run regenerated")
    ap.add_argument("--reference-root", required=True, type=Path, help="untouched package root (committed exhibits)")
    ap.add_argument("--closure", type=Path, default=None,
                    help="manuscript closure; default <reference-root>/certification/MANUSCRIPT_CLOSURE.sha256")
    ap.add_argument("--out", type=Path, default=None, help="also write the report here")
    a = ap.parse_args(argv)
    closure = a.closure or a.reference_root / "certification" / "MANUSCRIPT_CLOSURE.sha256"
    exhibits = closure_exhibits(closure)
    lines, failures = [], 0
    if not exhibits:
        lines.append(f"FAIL the closure lists no output/ exhibits: {closure}")
        failures += 1
    for rel in sorted(STATIC_EXHIBITS - {r for r, _ in exhibits}):
        lines.append(f"FAIL a declared static exhibit is not in the closure: {rel}")
        failures += 1
    for rel, pin in exhibits:
        problem = exhibit_problem(rel, pin, a.regen_root, a.reference_root)
        lines.append(f"FAIL {problem}" if problem else f"ok   {rel}")
        failures += bool(problem)
    figures = sum(1 for r, _ in exhibits if r.lower().endswith(".png"))
    tables = sum(1 for r, _ in exhibits if r.lower().endswith(".tex"))
    static = sum(1 for r, _ in exhibits if r in STATIC_EXHIBITS)
    lines.append(f"{len(exhibits)} closure exhibits: {tables} tables compared byte-for-byte, {figures - static} "
                 f"computed figures compared pixel-for-pixel, {static} static copies checked against their pins")
    lines.append(f"EXHIBIT_FIDELITY_FAILURES={failures}")
    text = "\n".join(lines) + "\n"
    sys.stdout.write(text)
    if a.out:
        a.out.write_text(text, encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
