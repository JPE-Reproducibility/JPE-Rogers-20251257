#!/usr/bin/env python3
"""Generate the shareable structural contract in an authorized environment.

This Stage-A program reads only five author-created aggregate MarketScan analysis
interfaces and the Nexis files represented by the public simulation. It records
paths, rounded row counts, exact columns, coarse data kinds, and formats, never values. It does
not inspect MarketScan raw tables, proprietary raw variable names, or provider
extraction code. The resulting contract is an input to the public Stage-B
simulator and must pass the rights/privacy review before publication.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd


MARKETSCAN_FILES = (
    "outpatient_combined_censored.csv",
    "constrained_adv_event_new_sept25.csv",
    "constrained_adv_event_new_sept25_3_2.csv",
)


def _rounded_count(value: int, salt: str = "", significant_figures: int = 2) -> int:
    """Privacy-preserving row-count approximation; never disclose the exact licensed size.

    Rounds to `significant_figures` (floor base 10), then adds exactly ONE rounding step. The committed
    count is therefore an APPROXIMATION that is GUARANTEED not to equal the exact real count (it lies
    between half a step and one-and-a-half steps above it -- also when the real count is already round,
    where plain rounding would be a no-op and leak the exact size), and it has BOUNDED single-record
    influence (threat T6): removing one real record moves the rounded value by at most one step, so the
    committed count changes by at most one step and, in most cases, not at all. (The earlier design added
    a hash-seeded offset keyed on the EXACT count; that made n and n-1 almost always commit different
    values -- an exact-invariance leak found by the confidential suite's C4 check on 2026-09-30.)
    Discloses only an approximate magnitude -- the intended 'rounded synthetic dimensions'.
    Deterministic in value (`salt` is kept for signature compatibility and is not used)."""
    value = int(value)
    if value <= 0:
        return 0
    digits = len(str(value))
    base = max(10 ** max(digits - significant_figures, 0), 10)
    rounded = max(base, int(round(value / base) * base))
    out = rounded + base          # one step above the 2-s.f. rounding: never the exact count, bounded influence
    if not out > value:           # explicit (not `assert`: python -O would strip it)
        raise ValueError(f"_rounded_count invariant violated for {value}")
    return out


def _kind(dtype) -> str:
    if pd.api.types.is_bool_dtype(dtype):
        return "integer"
    if pd.api.types.is_integer_dtype(dtype):
        return "integer"
    if pd.api.types.is_numeric_dtype(dtype):
        return "number"
    if pd.api.types.is_datetime64_any_dtype(dtype):
        return "date"
    return "string"


def _read(path: Path) -> pd.DataFrame:
    suffix = path.suffix.lower()
    if suffix == ".xlsx":
        return pd.read_excel(path)
    if suffix == ".csv":
        return pd.read_csv(path, low_memory=False)
    raise ValueError(f"unsupported contract input: {path}")


def _spec(path: Path, emit_cardinalities: bool = True) -> dict:
    # emit_cardinalities: per-column rounded cardinalities are REALIZED only by the Nexis path
    # (gen_00f draws each column via independent_universe.generate_identity_column). MarketScan is
    # generated by gen_00c on its own synthetic HCPCS/PRODUCTCODE construction and does NOT consume
    # these cardinalities, so committing them for MarketScan would be unrealized (and untrue) metadata
    # -- the payload-contract validator would (correctly) flag the disagreement. So it emits
    # cardinalities ONLY where they are honored (Nexis).
    frame = _read(path)
    if len(frame.columns) != len(set(frame.columns)):
        raise SystemExit(f"duplicate column names in contract input: {path}")
    kinds = {c: _kind(frame[c].dtype) for c in frame.columns}
    # Rounded per-column cardinality for high-cardinality STRING columns. The audit fails a file whose
    # synthetic distinct-count == exact real for a column with real distinct >= 50 (CITE, CASE NAME,
    # DATE DECIDED, SUMMARY, ...). Committing a ROUNDED (!= exact) cardinality lets gen_00f draw the
    # column via independent_universe.generate_identity_column, so neither the exact real distinct-count
    # nor the exact real group-size multiset is reproduced. Row-count coarsening alone only covers the
    # all-unique columns; a colliding column (e.g. dates) needs this per-column rounded cardinality.
    # salt on the STEM (not full name) so a .csv/.xlsx twin pair gets the SAME coarsened row
    # count (the build_contract twin check requires equal rows); (salt, value) still separates
    # genuinely different files. Computed first so per-column cardinalities can be capped by it.
    rows = _rounded_count(len(frame), salt=str(path.stem))
    cardinalities = {}
    for c in frame.columns if emit_cardinalities else []:
        # string AND date columns can trip the audit's exact-distinct-count check (dates collide, so
        # coarsening the row count alone doesn't guarantee a date column's distinct != exact real).
        # Nexis has no high-cardinality numeric columns, so string+date covers every flagged case.
        if kinds[c] not in ("string", "date"):
            continue
        n_distinct = int(frame[c].dropna().nunique())
        if n_distinct >= 50:
            # CAP the coarsened cardinality at the (coarsened) row count: a column cannot hold more
            # distinct values than there are rows. _rounded_count can round a near-full distinct count
            # UP past the row count (e.g. 480 rows -> 490), which is structurally impossible; the
            # generator would then silently clamp to n_rows, desyncing the committed contract from the
            # shipped payload. Capping keeps the committed cardinality possible so contract == payload.
            cardinalities[c] = min(_rounded_count(n_distinct, salt=f"{path.stem}|{c}"), rows)
    return {
        "rows": rows,
        "columns": list(frame.columns),
        "column_kinds": kinds,
        "cardinalities": cardinalities,
        "format": path.suffix.lower().lstrip("."),
    }


def _nexis_inputs(liability: Path) -> list[Path]:
    encodings = sorted(liability.glob("Liability_Encodings*.csv"))
    workbooks = sorted(
        p for p in liability.rglob("Results list*.xlsx")
        if ".ipynb_checkpoints" not in p.parts
    )
    paths = list(encodings)
    for workbook in workbooks:
        mirror = workbook.with_suffix(".csv")
        if not mirror.is_file():
            raise SystemExit(f"Nexis workbook lacks required CSV mirror: {workbook}")
        paths.extend((mirror, workbook))
    if not paths:
        raise SystemExit(f"no contract-eligible Nexis files under {liability}")
    return sorted(set(paths))


def build_contract(authorized_root: Path) -> dict:
    derived = authorized_root / "data" / "derived"
    liability = authorized_root / "data" / "raw" / "Liability"
    market_specs = {}
    for name in MARKETSCAN_FILES:
        path = derived / name
        if not path.is_file():
            raise SystemExit(f"missing aggregate MarketScan interface: {path}")
        market_specs[name] = _spec(path, emit_cardinalities=False)

    nexis_specs = {}
    for path in _nexis_inputs(liability):
        rel = path.relative_to(liability).as_posix()
        nexis_specs[rel] = _spec(path)

    # Same-stem Nexis twins must describe the same table. The public generator
    # writes the CSV as a serialization of its deterministic XLSX twin.
    for rel, spec in nexis_specs.items():
        if not rel.endswith(".xlsx"):
            continue
        twin = rel[:-5] + ".csv"
        if twin not in nexis_specs:
            raise SystemExit(f"Nexis contract missing CSV twin: {twin}")
        other = nexis_specs[twin]
        if spec["rows"] != other["rows"] or spec["columns"] != other["columns"]:
            raise SystemExit(f"Nexis XLSX/CSV structural mismatch: {rel} vs {twin}")

    return {
        "_schema": "simulation-schema-contract/v2",
        "_source": (
            "authorized Stage-A structural inventory: rounded dimensions plus columns/types of "
            "author-created aggregate MarketScan interfaces and simulated Nexis inputs; no values"
        ),
        "_row_policy": (
            "two-significant-figure close approximation (rounded to two significant figures plus one rounding step; "
            "a single real record moves it by at most one step); exact restricted extract sizes are not "
            "published; Data Editor acceptance required"
        ),
        "marketscan_files": market_specs,
        "nexis_files": nexis_specs,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--authorized-root", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("synthetic_pipeline/_synthetic_source_internal/simulation_schema_contract.json"),
    )
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    authorized_root = args.authorized_root.resolve()
    output = args.output.resolve()
    if output.exists() and not args.force:
        raise SystemExit(f"refusing to overwrite existing contract without --force: {output}")
    contract = build_contract(authorized_root)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(contract, indent=2, sort_keys=True) + "\n")
    print(
        f"wrote {output}: {len(contract['marketscan_files'])} MarketScan interfaces, "
        f"{len(contract['nexis_files'])} Nexis files"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
