#!/usr/bin/env python
"""
11g_descriptive_figures.py -- Copy pre-made Data Catalog diagram.

Copies the manually-created Data Catalog diagram (Data_new_latest.png)
from the raw-data directory into output/figures/.

(Distribution histograms are produced by 11f_reg_background.py.)

Inputs:
    data/raw/Data_new_latest.png                   (pre-made data catalog)

Outputs:
    output/figures/Data_new_latest.png
"""

import sys
import logging
import time
import shutil
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler(config.LOGS_DIR / "11g_descriptive_figures.log"),
        logging.StreamHandler(sys.stdout),
    ],
)


# ============================================================================
# Data Catalog (copy pre-made diagram)
# ============================================================================

def copy_data_catalog():
    """
    Copy the pre-made Data Catalog diagram (Data_new_latest.png) from
    raw data into the output figures directory.

    This figure (manuscript Figure D.2) is a manually-created diagram, not
    generated by code: the shipped PNG is the only artifact, and this step
    copies it into output/figures/. It is a required manuscript exhibit, so a
    missing source is a hard failure, not a warning -- otherwise the step exits
    0, the figure is silently absent from output/, and the run reports success.
    """
    logging.info("  Copying Data_new_latest.png (data catalog diagram)")

    # Check multiple possible source locations
    source_candidates = [
        config.RAW_DATA_DIR / "Data_new_latest.png",
        config.DATA_DIR / "Data_new_latest.png",
        config.ROOT_DIR / "Data_new_latest.png",
    ]

    source = None
    for candidate in source_candidates:
        if candidate.exists():
            source = candidate
            break

    if source is None:
        raise FileNotFoundError(
            "Data_new_latest.png not found. It is the source of manuscript Figure D.2, a "
            "manually-created diagram with no generating program, and it ships in the package at "
            "data/raw/Data_new_latest.png. Looked in: "
            + ", ".join(str(c) for c in source_candidates)
        )

    dest = config.FIGURES_DIR / "Data_new_latest.png"
    shutil.copy2(source, dest)
    logging.info(f"    Copied {source} -> {dest}")
    return True


# ============================================================================
# Main
# ============================================================================

def main():
    config.LOGS_DIR.mkdir(parents=True, exist_ok=True)
    config.FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    t_start = time.time()
    logging.info("=" * 60)
    logging.info("Starting descriptive figures...")

    # ================================================================
    # Data Catalog (copy)
    # ================================================================
    logging.info("Copying Data_new_latest.png...")
    copy_data_catalog()

    elapsed = time.time() - t_start
    logging.info("=" * 60)
    logging.info(f"Descriptive figures complete in {elapsed:.1f}s.")


if __name__ == "__main__":
    sys.exit(main())
